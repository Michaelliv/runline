#!/usr/bin/env node

/**
 * Generates the plugin table in docs/bundled-plugins.md from built plugin
 * metadata.
 *
 * Usage:
 *   node scripts/generate-plugin-table.js          # print to stdout
 *   node scripts/generate-plugin-table.js --write   # update the page in place
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { discoverPlugins } from "../dist/plugin/loader.js";
import { connectionFields } from "../dist/plugin/schema.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ICONS_DIR = join(__dirname, "..", "..", "codemode-plugins", "icons");
const PAGE = join(__dirname, "..", "..", "..", "docs", "bundled-plugins.md");
const ICONS_URL_BASE =
  "https://raw.githubusercontent.com/shift-labs-ai/codemode/main/packages/codemode-plugins/icons";

function iconFor(name) {
  for (const ext of ["svg", "png"]) {
    const file = `${name}.${ext}`;
    if (existsSync(join(ICONS_DIR, file))) {
      return `<img src="${ICONS_URL_BASE}/${file}" width="16" height="16" style="vertical-align: middle"> `;
    }
  }
  return "";
}

// Only what ships with codemode: discovery also finds the plugins in the
// folder of whoever runs this.
const plugins = (await discoverPlugins(null)).filter(
  (plugin) => plugin.sourceInfo?.origin === "builtin",
);
plugins.sort((a, b) => a.name.localeCompare(b.name));

const lines = [];
lines.push(`| Plugin | Actions | Resources | Connection fields |`);
lines.push(`|---|--:|---|---|`);

for (const p of plugins) {
  const resources = [...new Set(p.actions.map((a) => a.name.split(".")[0]))];
  const resourceList = resources.join(", ");

  const fields = connectionFields(p.connectionConfigSchema);
  const authFields = Object.keys(fields).length
    ? Object.entries(fields)
        .filter(([, field]) => field.required !== false)
        .map(([key, field]) =>
          field.env ? `\`${key}\` (\`${field.env}\`)` : `\`${key}\``,
        )
        .join(", ")
    : "—";

  // An OAuth plugin's connection is made by logging in, not by setting fields.
  const connection = p.oauth
    ? [`\`codemode auth ${p.name}\``, authFields === "—" ? "" : authFields]
        .filter(Boolean)
        .join(", ")
    : authFields;

  lines.push(
    `| ${iconFor(p.name)}**${p.name}** | ${p.actions.length} | ${resourceList} | ${connection} |`,
  );
}

const table = lines.join("\n");

if (process.argv.includes("--write")) {
  const page = readFileSync(PAGE, "utf-8");
  const start = "<!-- BEGIN PLUGIN TABLE -->";
  const end = "<!-- END PLUGIN TABLE -->";
  const startIdx = page.indexOf(start);
  const endIdx = page.indexOf(end);

  if (startIdx < 0 || endIdx < 0) {
    console.error(
      `Could not find <!-- BEGIN PLUGIN TABLE --> / <!-- END PLUGIN TABLE --> markers in ${PAGE}`,
    );
    process.exit(1);
  }

  const updated =
    page.slice(0, startIdx) +
    `${start}\n<!-- Generated by: node scripts/generate-plugin-table.js -->\n${table}\n${end}` +
    page.slice(endIdx + end.length);

  writeFileSync(PAGE, updated);
  console.log(`Updated ${PAGE} with ${plugins.length} plugins.`);
} else {
  console.log(table);
}
